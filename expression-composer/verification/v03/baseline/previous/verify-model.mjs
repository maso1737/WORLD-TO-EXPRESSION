import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';
globalThis.window = { EC: {} };
for (const name of ['sim', 'compare', 'composition', 'snapshot']) vm.runInThisContext(fs.readFileSync(new URL('../js/' + name + '.js', import.meta.url), 'utf8'));
const { createSim, stepSim, hashParticles } = window.EC.sim;
const { createComparison, stepComparison, comparisonStats } = window.EC.compare;
const { takeSnapshot, validateDocument } = window.EC.snapshot;
const { DEFAULT_EDIT } = window.EC.composition;
const report = { node: process.version, date: new Date().toISOString(), checks: [] };
const simulations = [stepSim(createSim(42), 600), stepSim(createSim(42), 600)];
const hashes = simulations.map(s => hashParticles(s.particles));
report.checks.push({ name: 'Same engine fresh simulation equality', pass: hashes[0] === hashes[1], hashes });
const pair = createComparison(42, undefined, 600); stepComparison(pair, 600);
report.comparison = comparisonStats(pair);
report.checks.push({ name: 'A/B synchronous steps', pass: report.comparison.stepA === report.comparison.stepB });
const snapshot = takeSnapshot(simulations[0], 'main');
simulations[0].rules.align = 0; stepSim(simulations[0], 1);
report.checks.push({ name: 'Deep immutable snapshot', pass: Object.isFrozen(snapshot.particles[0]) && hashParticles(snapshot.particles) === hashes[0] });
const restored = validateDocument({ schemaVersion: 1, snapshot, preset: 'SILENCE', edit: { ...DEFAULT_EDIT } });
report.checks.push({ name: 'Validated coordinate roundtrip', pass: restored.snapshot.hash === snapshot.hash && JSON.stringify(restored.snapshot.particles) === JSON.stringify(snapshot.particles) });
report.summary = { pass: report.checks.filter(x => x.pass).length, fail: report.checks.filter(x => !x.pass).length };
fs.writeFileSync(fileURLToPath(new URL('./node-results.json', import.meta.url)), JSON.stringify(report, null, 2) + '\n');
console.log(JSON.stringify(report)); if (report.summary.fail) process.exitCode = 1;
