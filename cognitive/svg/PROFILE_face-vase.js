const PROF_N = VASE_HW.length - 1;

// 図形の高さ ÷ viewBox幅。半幅は viewBox幅で正規化してあるので、
// 元の比率を保つには「高さ」からスケールする: hwPx = contourHW(t,...) * (描画高 / PROF_ASPECT)
const PROF_ASPECT = 0.9025;

// 半幅テーブルの線形補間
function hwOf(tbl, t) {
  const x = Math.max(0, Math.min(1, t)) * PROF_N;
  const i = Math.floor(x), f = x - i;
  return tbl[i] + (tbl[Math.min(PROF_N, i + 1)] - tbl[i]) * f;
}

// shapeCue: 0..100（0=壺寄り, 50=両義, 100=顔寄り）
// scale: 面積キュー（1.0 が原寸。>1 で中央領域が太る＝側の顔が細くなる）
// 戻り値: 中央領域の半幅（プレート幅に対する比）
function contourHW(t, shapeCue, scale = 1) {
  const m = shapeCue / 100;
  return (hwOf(VASE_HW, t) * (1 - m) + hwOf(FACE_HW, t) * m) * scale;
}
